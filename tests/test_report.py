def test_pii_scan_import_consistency():
    """Test that demonstrates the root cause of the PIIScanResult error.

    ERROR: pydantic_core._pydantic_core.ValidationError:
    pii_scan: Input should be a dictionary or an instance of PIIScanResult
    [type=dataclass_type, input_value=PIIScanResult(...), input_type=PIIScanResult]

    ROOT CAUSE: Inconsistent imports!

    In src/agents/intake.py line 12:
        from graph.state import PIIScanResult  ← WRONG: relative import (no src. prefix)

    This causes PIIScanResult to be imported twice:
    1. As: src.graph.state.PIIScanResult (via report.py imports)
    2. As: graph.state.PIIScanResult (via intake.py relative import)

    Pydantic treats these as different classes and rejects the dataclass validation!

    THE FIX: Use consistent absolute imports everywhere.
    Change line 12 in src/agents/intake.py from:
        from graph.state import PIIScanResult, PipeLineState
    To:
        from src.graph.state import PIIScanResult, PipeLineState
    """
    # This test verifies that PIIScanResult is correctly imported
    # If the imports are inconsistent, Pydantic will reject it

    # Import using the correct path
    from src.graph.state import PIIScanResult as CorrectPIIScanResult

    pii_result = CorrectPIIScanResult(pii_detected=True, affected_fields=["email"])

    state = {
        "audio_input": AudioInput(audio_bytes=b"123", filename="demo.wav", call_id="call-123"),
        "transcription": TranscriptionResult(
            segments=[TranscriptionSegment(start=0.0, end=1.0, text="hello", confidence=0.95)],
            call_id="call-123",
        ),
        "pii_scan": pii_result,
    }

    # This test will pass when imports are consistent
    updated = compile_report(state)
    assert updated["call_report"].pii_scan is not None
    assert updated["call_report"].pii_scan.pii_detected is True


