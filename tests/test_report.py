    def test_generate_report_pdf_without_pii_scan(self):
        """Test that PDF handles missing PII scan gracefully."""
        state = self.create_sample_state(include_pii=False)
        result = generate_report_pdf(state)

        assert isinstance(result, bytes)
        assert len(result) > 0

    def test_generate_report_pdf_no_call_report(self):
        """Test that PDF generation handles missing call_report."""
